# energy model F-MODEL-1/F-MODEL-2/F-MODEL-3


def _energy_expressions() -> dict[str, Any]:
    a2 = (4 * K2 - 3 * K1 - K3) / (2 * CH_MAX)
    a3 = 2 * (K1 - 2 * K2 + K3) / (3 * CH_MAX**2)
    energy = C0 + K1 * CH + a2 * CH**2 + a3 * CH**3

    reported = sp.Matrix([C0, K1, a2, a3])
    internal = sp.Matrix([C0, K1, K2, K3])

    energy_reported = RC0 + RC1 * CH + RC2 * CH**2 + RC3 * CH**3

    k1_from_reported = RC1
    k2_from_reported = RC1 + CH_MAX * RC2 + sp.Rational(3, 4) * CH_MAX**2 * RC3
    k3_from_reported = RC1 + 2 * CH_MAX * RC2 + 3 * CH_MAX**2 * RC3

    t_axis = (E_ARG + sp.Abs(E_ARG)) / (2 * E_REF)
    variance = (
        (1 - t_axis) ** 2 * B0**2 + 2 * (1 - t_axis) * t_axis * B1**2 + t_axis**2 * B2**2
    )
    sigma = sp.sqrt(variance)

    return {
        "energy": energy,
        "energy_derivative": sp.expand(sp.diff(energy, CH)),
        "gradients": [sp.expand(sp.diff(energy, q)) for q in (C0, K1, K2, K3)],
        "reported": tuple(reported),
        "jacobian": reported.jacobian(internal),
        "reported_gradients": [
            sp.expand(sp.diff(energy_reported, q)) for q in (RC0, RC1, RC2, RC3)
        ],
        "inverse": (RC0, k1_from_reported, k2_from_reported, k3_from_reported),
        "variance": variance,
        "variance_gradients": [sp.diff(variance, b) for b in (B0, B1, B2)],
        "sigma": sigma,
        "sigma_gradients": [sp.diff(sigma, b) for b in (B0, B1, B2)],
    }


def _model_module() -> str:
    e = _energy_expressions()
    gradients = ", ".join(_print(g) for g in e["gradients"])
    reported_gradients = ", ".join(_print(g) for g in e["reported_gradients"])
    reported = ", ".join(_print(v) for v in e["reported"])
    inverse = ", ".join(_print(v) for v in e["inverse"])
    jacobian_rows = ",\n            ".join(
        "[" + ", ".join(_print(e["jacobian"][i, j]) for j in range(4)) + "]"
        for i in range(4)
    )
    variance_gradients = ", ".join(_print(g) for g in e["variance_gradients"])
    sigma_gradients = ", ".join(_print(g) for g in e["sigma_gradients"])

    return (
        _header(("F-MODEL-1", "F-MODEL-2", "F-MODEL-3", "F-MODEL-4"), needs_erf=False)
        + f'''

def energy_kev(channel, c0, k1, k2, k3, channel_max):
    """F-MODEL-1: cubic in the internal slope basis (keV)."""
{_arrayify("channel")}    return {_print(e["energy"])}


def energy_derivative_kev_per_channel(channel, k1, k2, k3, channel_max):
    """F-MODEL-3: dE/dch (keV per channel)."""
{_arrayify("channel")}    return {_print(e["energy_derivative"])}


def energy_grad_internal(channel, channel_max):
    """F-MODEL-2: dE/d(c0, k1, k2, k3), shape (4, *channel.shape)."""
{_arrayify("channel")}    return np.stack(np.broadcast_arrays({gradients}), axis=0)


def energy_grad_reported(channel):
    """F-MODEL-2: dE/d(c0, c1, c2, c3), shape (4, *channel.shape)."""
{_arrayify("channel")}    return np.stack(np.broadcast_arrays({reported_gradients}), axis=0)


def internal_to_reported(c0, k1, k2, k3, channel_max):
    """F-MODEL-2: (c0, k1, k2, k3) -> (c0, c1, c2, c3)."""
    return ({reported})


def reported_to_internal(c0, c1, c2, c3, channel_max):
    """F-MODEL-2: inverse of internal_to_reported."""
    return ({inverse})


def internal_jacobian(channel_max):
    """F-MODEL-2: constant d(reported)/d(internal), shape (4, 4)."""
    return np.array(
        [
            {jacobian_rows},
        ],
        dtype=np.float64,
    )


def resolution_variance(energy_kev, b0, b1, b2, resol_e_ref_kev):
    """F-MODEL-4: sigma**2(E) in keV**2, used exactly as written."""
{_arrayify("energy_kev")}    return {_print(e["variance"])}


def resolution_variance_grad(energy_kev, b0, b1, b2, resol_e_ref_kev):
    """F-MODEL-4: d(sigma**2)/d(b0, b1, b2), shape (3, *energy.shape)."""
{_arrayify("energy_kev")}    return np.stack(np.broadcast_arrays({variance_gradients}), axis=0)


def resolution_sigma(energy_kev, b0, b1, b2, resol_e_ref_kev):
    """F-MODEL-4: sigma(E) in keV."""
{_arrayify("energy_kev")}    return {_print(e["sigma"])}


def resolution_sigma_grad(energy_kev, b0, b1, b2, resol_e_ref_kev):
    """F-MODEL-4: sigma and d(sigma)/d(b0, b1, b2), shape (3, *energy.shape)."""
{_arrayify("energy_kev")}    return (
        {_print(e["sigma"])},
        np.stack(np.broadcast_arrays({sigma_gradients}), axis=0),
    )
'''
    )


