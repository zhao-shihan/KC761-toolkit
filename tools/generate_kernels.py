#!/usr/bin/env python3
"""Generate ``kc761/core/_gen`` from single-source sympy expressions.

Usage: ``python tools/generate_kernels.py``

The generated modules are committed (D-77). Every value and every derivative
comes from the same symbolic expression; the generator only composes the
primitive derivatives that ``sympy.diff`` produced. ``kc761.core._gen`` checks
the manifest at import time and regenerates in place when the generator or a
generated module changed (sympy is a runtime dependency).

No timestamps or environment-dependent strings are written, so repeated runs
with the same sympy version are byte-identical.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path
from typing import Any

import sympy as sp
from sympy.printing.numpy import NumPyPrinter
from sympy.printing.pycode import pycode

REPO_ROOT = Path(__file__).resolve().parents[1]
GEN_DIR = REPO_ROOT / "kc761" / "core" / "_gen"
GENERATOR_REL = "tools/generate_kernels.py"
MANIFEST_NAME = "_manifest.json"
COMMAND = "python tools/generate_kernels.py"
FORMULA_IDS = (
    "F-MODEL-1",
    "F-MODEL-2",
    "F-MODEL-3",
    "F-MODEL-4",
    "F-KERN-1",
    "F-KERN-2",
    "F-KERN-4",
)

# ---------------------------------------------------------------------------
# code printer


class _NumPyPrinter(NumPyPrinter):
    """NumPy printer with the primitives the kernels need."""

    def _print_erf(self, expr: sp.Expr) -> str:
        return f"erf({self._print(expr.args[0])})"

    def _print_Max(self, expr: sp.Expr) -> str:
        return "numpy.maximum(" + ", ".join(self._print(a) for a in expr.args) + ")"

    def _print_Min(self, expr: sp.Expr) -> str:
        return "numpy.minimum(" + ", ".join(self._print(a) for a in expr.args) + ")"

    def _print_Abs(self, expr: sp.Expr) -> str:
        return f"numpy.abs({self._print(expr.args[0])})"

    def _print_sign(self, expr: sp.Expr) -> str:
        return f"numpy.sign({self._print(expr.args[0])})"


_PRINTER = _NumPyPrinter()


def _print(expr: sp.Expr) -> str:
    return _PRINTER.doprint(expr).replace("numpy.", "np.")


def _scalar_print(expr: sp.Expr) -> str:
    """Render a scalar (``math``/builtin) variant of the same sympy expression.

    This is the numba-compatible rendering of the single source: ``pycode``
    maps ``exp``/``sqrt``/``erf`` to ``math.*`` and ``Min``/``Max``/``Abs``/
    ``sign`` to the Python builtins, which ``numba.njit`` accepts.
    """
    return pycode(expr, standard="python3")

def _arrayify(*names: str) -> str:
    return "".join(f"    {name} = np.asarray({name}, dtype=np.float64)\n" for name in names)


def _header(ids: tuple[str, ...], *, needs_erf: bool, needs_math: bool = False) -> str:
    lines = [
        "# GENERATED by tools/generate_kernels.py -- do not edit.",
        f"# sympy version: {sp.__version__}",
        f"# formula ids: {', '.join(ids)}",
        f"# command: {COMMAND}",
        "# ruff: noqa: E501, F401, I001",
        "",
        "from __future__ import annotations",
        "",
    ]
    if needs_math:
        lines += ["import math", ""]
    lines += [
        "import numpy as np",
        "from numpy.typing import NDArray",
    ]
    if needs_erf:
        lines.append("from scipy.special import erf")
    lines.append("")
    return "\n".join(lines)


# ---------------------------------------------------------------------------
# symbols

CH = sp.Symbol("channel", real=True)
CH_MAX = sp.Symbol("channel_max", positive=True)
C0, K1, K2, K3 = sp.symbols("c0 k1 k2 k3", real=True)
RC0, RC1, RC2, RC3 = sp.symbols("c0 c1 c2 c3", real=True)
E_ARG = sp.Symbol("energy_kev", real=True)
B0, B1, B2 = sp.symbols("b0 b1 b2", real=True)
E_REF = sp.Symbol("resol_e_ref_kev", positive=True)
E_LO, E_HI, C_SRC, SIGMA = sp.symbols("e_lo e_hi c sigma", positive=True)
N_SIGMA = sp.Symbol("n_sigma", positive=True)
OFFSET = sp.Symbol("offset", real=True)
CENTER = sp.Symbol("center", real=True)
S_RAW = sp.Symbol("s_raw", real=True)
W_SC = sp.Symbol("w_sc", real=True)
T_PARAM = sp.Symbol("t_param", real=True)


def _s_raw(offset_expression: sp.Expr) -> sp.Expr:
    return (N_SIGMA * SIGMA - sp.Abs(offset_expression)) / SIGMA


def _clip_smoothstep(offset_expression: sp.Expr) -> sp.Expr:
    """Clipped smoothstep coordinate, 0 beyond ``n_sigma``, 1 on the plateau."""
    return sp.Min(1, sp.Max(0, _s_raw(offset_expression)))


def _taper_expression(offset_expression: sp.Expr) -> sp.Expr:
    w_expr = 3 * W_SC**2 - 2 * W_SC**3
    return w_expr.subs(W_SC, _clip_smoothstep(offset_expression))


def _taper_derivative(offset_expression: sp.Expr, variable: sp.Symbol) -> sp.Expr:
    """Chain rule with the clipping prefactor.

    ``sympy.diff`` of the clipped expression would produce ``Piecewise``
    branches; the prefactor ``6 s - 6 s**2`` vanishes exactly where the clip
    saturates, so evaluating the unclipped chain rule at the clipped
    coordinate is the correct extension and keeps a single symbolic source.
    """
    w_expr = 3 * W_SC**2 - 2 * W_SC**3
    dw_ds = sp.diff(w_expr, W_SC)
    ds_dvariable = sp.diff(_s_raw(offset_expression), variable)
    return (dw_ds * ds_dvariable).subs(W_SC, _clip_smoothstep(offset_expression))


