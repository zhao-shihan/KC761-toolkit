# response kernel F-KERN-1/F-KERN-2/F-KERN-4


def _phi(z: sp.Expr) -> sp.Expr:
    return (1 + sp.erf(z / sp.sqrt(2))) / 2


def _kernel_expressions() -> dict[str, Any]:
    z_hi = (E_HI - C_SRC) / SIGMA
    z_lo = (E_LO - C_SRC) / SIGMA
    probability = _phi(z_hi) - _phi(z_lo)
    probability_gradients = {
        "e_lo": sp.diff(probability, E_LO),
        "e_hi": sp.diff(probability, E_HI),
        "c": sp.diff(probability, C_SRC),
        "sigma": sp.diff(probability, SIGMA),
    }

    offset_expression = CENTER - C_SRC
    taper_centered = _taper_expression(offset_expression)
    unclipped_dc = (3 * W_SC**2 - 2 * W_SC**3)
    dw_ds = sp.diff(unclipped_dc, W_SC)
    dw_dc_centered = (dw_ds * sp.diff(_s_raw(offset_expression), C_SRC)).subs(
        W_SC, _clip_smoothstep(offset_expression)
    )
    dw_dsigma_centered = (dw_ds * sp.diff(_s_raw(offset_expression), SIGMA)).subs(
        W_SC, _clip_smoothstep(offset_expression)
    )

    tapered_bin = probability * taper_centered
    tapered_bin_gradients = {
        "e_lo": probability_gradients["e_lo"] * taper_centered,
        "e_hi": probability_gradients["e_hi"] * taper_centered,
        "c": probability_gradients["c"] * taper_centered + probability * dw_dc_centered,
        "sigma": probability_gradients["sigma"] * taper_centered
        + probability * dw_dsigma_centered,
    }
    dw_dcenter_centered = (
        dw_ds * sp.diff(_s_raw(offset_expression), CENTER)
    ).subs(W_SC, _clip_smoothstep(offset_expression))
    tapered_bin_gradients["center"] = probability * dw_dcenter_centered

    n_fun = sp.Function("numerator")(T_PARAM)
    d_fun = sp.Function("denominator")(T_PARAM)
    quotient = sp.diff(n_fun / d_fun, T_PARAM)
    quotient = quotient.subs(sp.Derivative(n_fun, T_PARAM), sp.Symbol("d_numerator"))
    quotient = quotient.subs(sp.Derivative(d_fun, T_PARAM), sp.Symbol("d_denominator"))
    quotient = quotient.subs(n_fun, sp.Symbol("numerator")).subs(d_fun, sp.Symbol("denominator"))
    quotient_source = _print(quotient).replace("d_numerator", "d_values").replace(
        "numerator", "values"
    )
    quotient_expr = quotient.subs(
        {
            sp.Symbol("numerator"): sp.Symbol("values"),
            sp.Symbol("d_numerator"): sp.Symbol("d_values"),
        }
    )

    return {
        "probability": probability,
        "probability_gradients": probability_gradients,
        "taper": _taper_expression(OFFSET),
        "taper_dx": _taper_derivative(OFFSET, OFFSET),
        "taper_dsigma": _taper_derivative(OFFSET, SIGMA),
        "tapered_bin": tapered_bin,
        "tapered_bin_gradients": tapered_bin_gradients,
        "quotient_source": quotient_source,
        "quotient_expr": quotient_expr,
    }


def _cse_lines(expressions: list[sp.Expr]) -> tuple[str, list[str]]:
    """Render sympy common-subexpression assignments plus the reduced returns.

    The generated kernel expressions share the taper and Gaussian factors many
    times; emitting them once through ``sympy.cse`` keeps the same formula (the
    generator is still the single source) while removing the repeated NumPy
    evaluations that dominated the response Jacobian (D-172).
    """
    replacements, reduced = sp.cse(expressions, optimizations="basic")
    body = "".join(f"    {symbol} = {_print(expr)}\n" for symbol, expr in replacements)
    return body, [_print(expr) for expr in reduced]


def _return_single(expressions: list[sp.Expr]) -> str:
    body, reduced = _cse_lines(expressions)
    return f"{body}    return {reduced[0]}\n"


def _return_tuple(expressions: list[sp.Expr]) -> str:
    body, reduced = _cse_lines(expressions)
    entries = "".join(f"        {expr},\n" for expr in reduced)
    return f"{body}    return (\n{entries}    )\n"


def _scalar_cse_lines(expressions: list[sp.Expr]) -> tuple[str, list[str]]:
    """Scalar (numba-compatible) counterpart of :func:`_cse_lines`."""
    replacements, reduced = sp.cse(expressions, optimizations="basic")
    body = "".join(f"    {symbol} = {_scalar_print(expr)}\n" for symbol, expr in replacements)
    return body, [_scalar_print(expr) for expr in reduced]


def _scalar_return_single(expressions: list[sp.Expr]) -> str:
    body, reduced = _scalar_cse_lines(expressions)
    return f"{body}    return {reduced[0]}\n"


def _scalar_return_tuple(expressions: list[sp.Expr]) -> str:
    body, reduced = _scalar_cse_lines(expressions)
    entries = "".join(f"        {expr},\n" for expr in reduced)
    return f"{body}    return (\n{entries}    )\n"


def _kernel_module() -> str:
    e = _kernel_expressions()
    n_grad = e["tapered_bin_gradients"]
    kernel_returns = [
        e["tapered_bin"],
        n_grad["e_lo"],
        n_grad["e_hi"],
        n_grad["c"],
        n_grad["sigma"],
        n_grad["center"],
    ]
    quotient_return = _return_single([e["quotient_expr"]])
    quotient_scalar_return = _scalar_return_single([e["quotient_expr"]])

    return (
        _header(("F-KERN-1", "F-KERN-2", "F-KERN-4"), needs_erf=True, needs_math=True)
        + f'''

import numba


def _jit(function):
    """Compile a scalar kernel with numba (cache=True; numba is a hard dep, D-174)."""
    return numba.njit(cache=True)(function)


def gaussian_bin_probability(e_lo, e_hi, c, sigma):
    """F-KERN-1: exact Gaussian bin integral (no taper)."""
{_arrayify("e_lo", "e_hi", "c", "sigma")}{_return_single([e["probability"]])}


def taper(offset, sigma, n_sigma):
    """F-KERN-2: smoothstep support taper, 1 on the plateau, 0 beyond n_sigma."""
{_arrayify("offset", "sigma")}{_return_single([e["taper"]])}


def taper_grad(offset, sigma, n_sigma):
    """F-KERN-4: taper value and d/d(offset), d/d(sigma)."""
{_arrayify("offset", "sigma")}{_return_tuple([e["taper"], e["taper_dx"], e["taper_dsigma"]])}


def tapered_bin(e_lo, e_hi, c, sigma, center, n_sigma):
    """F-KERN-2: tapered (unnormalized) bin probability."""
{_arrayify("e_lo", "e_hi", "c", "sigma", "center")}{_return_single([e["tapered_bin"]])}


def tapered_bin_grad(e_lo, e_hi, c, sigma, center, n_sigma):
    """F-KERN-4: tapered bin and partial derivatives.

    Returns ``(n, dn_de_lo, dn_de_hi, dn_dc, dn_dsigma, dn_dcenter)``. The
    smoothstep clipping contributes a prefactor that vanishes outside the
    transition band; every factor is sympy-generated.
    """
{_arrayify("e_lo", "e_hi", "c", "sigma", "center")}{_return_tuple(kernel_returns)}


@_jit
def scalar_tapered_bin(e_lo, e_hi, c, sigma, center, n_sigma):
    """F-KERN-2 scalar rendering of the same sympy expression (D-174)."""
{_scalar_return_single([e["tapered_bin"]])}

@_jit
def scalar_tapered_bin_grad(e_lo, e_hi, c, sigma, center, n_sigma):
    """F-KERN-4 scalar rendering of the same sympy expression (D-174)."""
{_scalar_return_tuple(kernel_returns)}

@_jit
def scalar_normalize_derivative(values, d_values, denominator, d_denominator):
    """F-KERN-2/F-KERN-4 scalar derivative rendering of the same sympy expression."""
{quotient_scalar_return}


def normalize(values, denominator):
    """F-KERN-2: column renormalization p = n / D, zero where D <= 0."""
    values = np.asarray(values, dtype=np.float64)
    denominator = np.asarray(denominator, dtype=np.float64)
    with np.errstate(divide="ignore", invalid="ignore"):
        return np.where(denominator > 0.0, values / denominator, 0.0)


def normalize_derivative(values, d_values, denominator, d_denominator):
    """F-KERN-2/F-KERN-4: renormalized derivative ``{e["quotient_source"]}``."""
{_arrayify("values", "d_values", "denominator", "d_denominator")}{quotient_return}
'''
    )


